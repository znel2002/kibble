#!/usr/bin/env python3
"""Exports every pet in tools/pets/ for the app.

Writes:
  Sources/Kibble/Sprites.generated.swift   frame data for every pet
  docs/pets/<id>.png                       contact sheet per pet
  Resources/menubar*.png                   status bar template icon
  Resources/AppIcon/                       app icon (from the Afghan Hound)

To add a pet, drop a module in tools/pets/ that defines PET (see pixelkit.py),
check it with `python3 tools/pixelkit.py preview <id>`, then run this script.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pixelkit import ROOT, W, H, REQUIRED_FRAMES, load, validate, render_sheet, rgba  # noqa: E402


def discover():
    ids = sorted(p.stem for p in (ROOT / "tools" / "pets").glob("*.py") if not p.stem.startswith("_"))
    pets, failed = [], {}
    for i in ids:
        try:
            pet = load(i)
        except Exception as e:  # a half-drawn pet should not break the others
            failed[i] = [f"import failed: {e}"]
            continue
        errs = validate(pet)
        if errs:
            failed[i] = errs
        else:
            pets.append(pet)
    # The Afghan first, then dogs, then cats, alphabetically.
    order = {"dog": 0, "cat": 1, "hamster": 2}
    pets.sort(key=lambda p: (p["id"] != "afghan", order.get(p["kind"], 9), p["name"]))
    return pets, failed


def avatar(pet):
    """A head-and-shoulders crop of the sitting pose: 18 rows tall, as wide as
    the head (at least 26 px), centred on it."""
    g = pet["frames"]["sit"]
    rows = [y for y in range(H) if any(c != " " for c in g[y])]
    top = rows[0]
    band = range(top, min(top + 18, H))
    head = [g[y] for y in range(top, min(top + 14, H))]
    xs = [x for r in head for x, c in enumerate(r) if c != " "]
    width = max(26, max(xs) - min(xs) + 1)
    x0 = max(0, min(W - width, (min(xs) + max(xs) + 1 - width) // 2))
    return ["".join(g[y][x0:x0 + width]) for y in band]


def swift_str(rows, indent):
    return "\n".join(f'{indent}"{"".join(r)}",' for r in rows)


def write_swift(pets, path):
    out = [
        "// Generated by tools/sprites.py. Do not edit by hand.",
        "",
        "struct PetArt {",
        "    let id: String",
        "    let name: String",
        "    let kind: String",
        "    let palette: [Character: UInt32]",
        "    let frames: [String: [String]]",
        "    let avatar: [String]",
        "}",
        "",
        "enum SpriteData {",
        f"    static let width = {W}",
        f"    static let height = {H}",
        "    static let pets: [PetArt] = [",
    ]
    for p in pets:
        out.append("        PetArt(")
        out.append(f'            id: "{p["id"]}",')
        out.append(f'            name: "{p["name"]}",')
        out.append(f'            kind: "{p["kind"]}",')
        out.append("            palette: [" + ", ".join(f'"{k}": 0x{v.upper()}' for k, v in p["palette"].items()) + "],")
        out.append("            frames: [")
        for name in REQUIRED_FRAMES:
            out.append(f'                "{name}": [')
            out.append(swift_str(p["frames"][name], "                    "))
            out.append("                ],")
        out.append("            ],")
        out.append("            avatar: [")
        out.append(swift_str(avatar(p), "                "))
        out.append("            ]")
        out.append("        ),")
    out += ["    ]", "}", ""]
    path.write_text("\n".join(out))


