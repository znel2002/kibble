def write_menubar_icon(fs, path):
    """Template image for the status bar, hand-drawn at 18pt."""
    from PIL import Image
    for scale, name in ((1, "menubar.png"), (2, "menubar@2x.png")):
        img = Image.new("RGBA", (18 * scale, 18 * scale), (0, 0, 0, 0))
        for y, row in enumerate(MENUBAR):
            for x, c in enumerate(row):
                if c == "X":
                    img.paste((0, 0, 0, 255), (x * scale, y * scale, (x + 1) * scale, (y + 1) * scale))
        img.save(path / name)


def write_app_icon(pet, out):
    fs, palette = pet["frames"], pet["palette"]
    from PIL import Image, ImageDraw, ImageFilter
    out.mkdir(parents=True, exist_ok=True)
    N = 1024
    base = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    # macOS icon grid: 824px squircle-ish body, centred
    body = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    mask = Image.new("L", (N, N), 0)
    ImageDraw.Draw(mask).rounded_rectangle((100, 100, 924, 924), radius=185, fill=255)
    grad = Image.new("RGBA", (N, N))
    top, bot = (54, 44, 92), (22, 20, 38)
    for y in range(N):
        t = y / N
        grad.paste(tuple(round(top[i] + (bot[i] - top[i]) * t) for i in range(3)) + (255,), (0, y, N, y + 1))
    body.paste(grad, (0, 0), mask)
    shadow = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rounded_rectangle((100, 112, 924, 936), radius=185, fill=(0, 0, 0, 120))
    shadow = shadow.filter(ImageFilter.GaussianBlur(18))
    base.alpha_composite(shadow)
    base.alpha_composite(body)
    # usage plinth: orange + green bars
    d = ImageDraw.Draw(base)
    d.rounded_rectangle((262, 742, 762, 806), radius=18, fill=(14, 13, 24, 255))
    d.rectangle((286, 762, 286 + 200, 786), fill=(217, 119, 87, 255))
    d.rectangle((538, 762, 538 + 150, 786), fill=(16, 163, 127, 255))
    # hound
    g = fs["sit"]
    sc = 14
    ys = [y for y, r in enumerate(g) if any(c != " " for c in r)]
    xs = [x for x in range(W) if any(g[y][x] != " " for y in range(H))]
    cw = (max(xs) - min(xs) + 1) * sc
    ox = (N - cw) // 2 - min(xs) * sc
    oy = 742 - (max(ys) + 1) * sc + sc
    for y, row in enumerate(g):
        for x, c in enumerate(row):
            if c != " ":
                d.rectangle((ox + x * sc, oy + y * sc, ox + (x + 1) * sc - 1, oy + (y + 1) * sc - 1), fill=rgba(palette, c))
    base.save(out / "icon_1024.png")
    iconset = out / "Kibble.iconset"
    iconset.mkdir(exist_ok=True)
    for pt in (16, 32, 128, 256, 512):
        for mul in (1, 2):
            px = pt * mul
            name = f"icon_{pt}x{pt}{'@2x' if mul == 2 else ''}.png"
            base.resize((px, px), Image.LANCZOS).save(iconset / name)


def main():
    pets, failed = discover()
    for p in pets:
        render_sheet(p, ROOT / "docs" / "pets" / f"{p['id']}.png")
    write_swift(pets, ROOT / "Sources" / "Kibble" / "Sprites.generated.swift")
    res = ROOT / "Resources"
    res.mkdir(exist_ok=True)
    afghan = next(p for p in pets if p["id"] == "afghan")
    write_menubar_icon(afghan["frames"], res)
    write_app_icon(afghan, res / "AppIcon")
    print("pets:", ", ".join(p["id"] for p in pets))
    for i, errs in failed.items():
        print(f"skipped {i}:", *errs, sep="\n  ")


if __name__ == "__main__":
    main()
